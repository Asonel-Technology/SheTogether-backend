import { z } from 'zod';
import { defineModule } from '../core/route.js';
import { isoDate, language, uuid } from '../core/schemas.js';
import * as analytics from '../services/analytics.service.js';
import { analyticsLimiter } from '../middleware/rateLimit.js';

const EVENT_TYPES = ['SESSION_START', 'CONTENT_VIEW', 'CATEGORY_VIEW', 'SEARCH', 'CHANNEL_VIEW', 'CHATBOT_USED', 'CONTENT_SAVED', 'OFFLINE_SYNC', 'ACCESSIBILITY_FEATURE', 'REFERRAL_VIEW'];

export const analytics_ = defineModule({
  tag: 'Analytics',
  description: '📊 **Usage Analytics** — Send batches of up to 20 privacy-safe usage events from the client. Age band and language are derived from the access token server-side and cannot be forged. Never include names, free text, health questions or personal identifiers in event payloads.',
  base: '/analytics',
  routes: [
    {
      method: 'post', path: '/events', summary: 'Record up to 20 usage events (batch)', status: 202, auth: 'optional', use: [analyticsLimiter],
      description: 'Age band and language are taken from the access token (not the request) so they cannot be forged. `topic` is a short slug such as a category or article slug.',
      body: z.object({
        events: z.array(z.object({
          type: z.enum(EVENT_TYPES),
          topic: z.string().regex(/^[a-z0-9][a-z0-9_:-]{0,63}$/).optional(),
          sessionRef: uuid.optional().describe('Random per-install id generated by the client; not linked to the account'),
          language: language.optional().describe('Only used for anonymous callers'),
        }).strict()).min(1).max(20),
      }).strict(),
      handler: ({ user, body }) => analytics.ingest(user, body.events),
    },
  ],
});

export const adminAnalytics = defineModule({
  tag: 'Admin · Analytics',
  description: '📊 **Admin — Analytics** — Aggregated usage reporting for administrators. Filter by date range to see event counts, top content, language breakdown and chatbot usage. Required role: ADMIN.',
  base: '/admin/analytics',
  routes: [
    {
      method: 'get', path: '/summary', summary: 'Aggregated usage summary', auth: ['ADMIN'],
      query: z.object({ from: isoDate.optional(), to: isoDate.optional() }),
      handler: ({ query }) => analytics.summary({ from: query.from ?? new Date(Date.now() - 30 * 86_400_000), to: query.to ?? new Date() }),
    },
  ],
});
